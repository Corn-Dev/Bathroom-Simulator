// Host world saves (slots with list, save, load, delete), separate from per-player save data (decision 12).
// Design: 01 §4.7; file layout, envelope and backends 04 §2 (SteamWorldSaveStore, LocalWorldSaveStore).
// Calls are synchronous. Validation: slotId must match ^[a-z0-9\-]{1,40}$ (else InvalidArgument, no I/O);
// payload null, empty or over 64 MiB → InvalidArgument; displayName trimmed and cut to 48 chars.

using System;
using System.Collections.Generic;

namespace MultiplayerKit
{
    /// <summary>Slot metadata (the small JSON side file); listing slots never reads payloads.</summary>
    public sealed class WorldSaveSlotInfo
    {
        private static readonly IReadOnlyDictionary<string, string> EmptySnapshot =
            new Dictionary<string, string>(StringComparer.Ordinal);

        /// <summary>^[a-z0-9\-]{1,40}$, generated by the store.</summary>
        public string SlotId { get; }

        /// <summary>Max 48 chars. Never null.</summary>
        public string DisplayName { get; }

        public DateTime CreatedUtc { get; }
        public DateTime UpdatedUtc { get; }
        public double PlaytimeSeconds { get; }

        /// <summary>adapter.GameVersion at save time. Never null.</summary>
        public string GameVersion { get; }

        /// <summary>HostSettings.ToSnapshot() at save time (never contains the password). Never null.</summary>
        public IReadOnlyDictionary<string, string> SettingsSnapshot { get; }

        public long PayloadBytes { get; }

        public WorldSaveSlotInfo(string slotId, string displayName, DateTime createdUtc, DateTime updatedUtc,
                                 double playtimeSeconds, string gameVersion,
                                 IReadOnlyDictionary<string, string> settingsSnapshot, long payloadBytes)
        {
            SlotId = slotId ?? "";
            DisplayName = displayName ?? "";
            CreatedUtc = createdUtc;
            UpdatedUtc = updatedUtc;
            PlaytimeSeconds = playtimeSeconds;
            GameVersion = gameVersion ?? "";
            SettingsSnapshot = CopySnapshot(settingsSnapshot);
            PayloadBytes = payloadBytes;
        }

        // Defensive copy so a listed slot cannot change under a presenter holding it.
        private static IReadOnlyDictionary<string, string> CopySnapshot(IReadOnlyDictionary<string, string> source)
        {
            if (source == null || source.Count == 0) return EmptySnapshot;
            var copy = new Dictionary<string, string>(source.Count, StringComparer.Ordinal);
            foreach (KeyValuePair<string, string> pair in source)
            {
                if (pair.Key == null) continue;
                copy[pair.Key] = pair.Value ?? "";
            }
            return copy;
        }
    }

    /// <summary>A loaded slot: metadata plus the adapter-defined binary payload.</summary>
    public sealed class WorldSaveData
    {
        public WorldSaveSlotInfo Info { get; }

        /// <summary>Opaque to Core; adapter-defined, binary. Not copied (can be tens of MB).</summary>
        public byte[] Payload { get; }

        public WorldSaveData(WorldSaveSlotInfo info, byte[] payload)
        {
            Info = info ?? throw new ArgumentNullException(nameof(info));
            Payload = payload ?? throw new ArgumentNullException(nameof(payload));
        }
    }

    public interface IWorldSaveStore
    {
        /// <summary>Default 16.</summary>
        int MaxSlots { get; }

        /// <summary>Sorted by UpdatedUtc, newest first. A missing save directory is an empty list.</summary>
        KitResult<IReadOnlyList<WorldSaveSlotInfo>> ListSlots();

        /// <summary>SaveNotFound if there is no slot.</summary>
        KitResult<WorldSaveSlotInfo> GetLatest();

        /// <summary>
        /// slotId null creates a new slot (SaveIoFailed with Detail "slots full" at MaxSlots); otherwise the
        /// slot is overwritten and keeps its CreatedUtc. A cloud write failure falls back to the local file
        /// and is still a success.
        /// </summary>
        KitResult<WorldSaveSlotInfo> Save(string slotId, string displayName, double playtimeSeconds,
            string gameVersion, IReadOnlyDictionary<string, string> settingsSnapshot, byte[] payload);

        /// <summary>SaveNotFound, SaveCorrupt or SaveIoFailed on failure.</summary>
        KitResult<WorldSaveData> Load(string slotId);

        KitResult Delete(string slotId);
    }
}
